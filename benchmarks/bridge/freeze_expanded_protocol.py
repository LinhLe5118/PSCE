"""Freeze the five-task BRIDGE follow-up before forecasts or learner labels."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

PANEL = Path(__file__).resolve().parent / "expanded_panel_2026-10-08"
HERE = PANEL.parent
OLD = HERE / "fresh_panel_2026-10-08/protocol.json"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_new(path: Path, value: dict) -> None:
    if path.exists():
        raise FileExistsError(f"Refusing to replace frozen protocol/addendum: {path}")
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> None:
    metadata = json.loads((PANEL / "manifest.json").read_text(encoding="utf-8"))
    downloaded = json.loads((PANEL / "download_manifest.json").read_text(encoding="utf-8"))
    preflight = json.loads((PANEL / "adapter_reward_preflight.json").read_text(encoding="utf-8"))
    generated = json.loads((PANEL / "generated_pipeline_manifest.json").read_text(encoding="utf-8"))
    with (PANEL / "candidate_registry.csv").open(newline="", encoding="utf-8") as handle:
        registry = list(csv.DictReader(handle))
    names = [row["mdp_name"] for row in registry]
    if (names != metadata["task_names"] or len(names) != 5 or
            [row["mdp_name"] for row in preflight["tasks"]] != names or
            any(row["status"] != "ELIGIBLE_NONNEGATIVE" for row in preflight["tasks"]) or
            len(downloaded["members"]) != 5 or len(generated["modules"]) != 13):
        raise ValueError("Expanded five-task panel is not fully preflighted")
    if any((PANEL / name).exists() for name in (
            "protocol.json", "reward_interpretation_addendum.json",
            "published_survival_comparator_addendum.json", "prelabel_seal.json")):
        raise FileExistsError("Expanded protocol has already been frozen")
    old = json.loads(OLD.read_text(encoding="utf-8"))
    protocol = dict(old)
    protocol.update({
        "status": "FRESH_BRIDGE_PROTOCOL_FROZEN_BEFORE_LABELS",
        "panel_name": "BRIDGE expanded prospective follow-up, five new MDPs",
        "evaluation_tasks": names,
        "excluded_candidates": [],
        "episode_horizon": {row["mdp_name"]: int(row["horizon"]) for row in registry},
        "environment_source": ("BRIDGE v1.1.1 published sticky-action 25% MDPs; "
                               "group-generated offline logs and learner labels"),
        "bootstrap": {"unit": "task", "replicates": 10000, "seed": 20261009},
        "seal_gate": ("All 75 predictions per forecaster and 25 original scalar-score rows "
                      "must be hashed before any learner label run"),
        "test_labels_read": False,
        "source_sha256": {
            "parent_five_task_protocol": sha256(OLD),
            "metadata_screen": sha256(PANEL / "manifest.json"),
            "inventory_155": sha256(PANEL / "inventory_155.csv"),
            "candidate_registry": sha256(PANEL / "candidate_registry.csv"),
            "download_manifest": sha256(PANEL / "download_manifest.json"),
            "adapter_reward_preflight": sha256(PANEL / "adapter_reward_preflight.json"),
            "generated_pipeline_manifest": sha256(PANEL / "generated_pipeline_manifest.json"),
            "freeze_script": sha256(Path(__file__)),
        },
        "limits": [
            "Follow-up panel selected after the earlier five-task result, using only prior-use status, published size and reward-domain metadata.",
            "The 155-MDP author benchmark evaluates online SQIRL/PPO/DQN/GORP and effective horizon, a different endpoint from offline learner requirement.",
            "Published MDPs are third-party; the offline trajectories and learner labels are generated by this project.",
            "An infeasible prelabel resource gate is recorded as NO-GO, never replaced by post-outcome task selection.",
            "No method retuning after any new learner labels are opened.",
        ],
    })
    protocol_file = PANEL / "protocol.json"
    write_new(protocol_file, protocol)
    protocol_hash = sha256(protocol_file)
    reward_addendum = {
        "status": "PRELABEL_REWARD_SCALE_INTERPRETATION_FROZEN",
        "protocol_sha256": protocol_hash,
        "reward_gate_sha256": sha256(PANEL / "adapter_reward_preflight.json"),
        "mathematical_invariance": "Positive scaling leaves normalized return invariant for each fixed policy.",
        "non_invariance": "Fixed reward-sensitive learner hyperparameters can change learned policies after scaling; the label and OEH forecast both target the normalized adapter.",
        "comparison_scope": "Same normalized adapter for all forecasters and offline learners; author EH/TQ/SACo are scalar secondary diagnostics, not equivalent seven-class forecasts.",
        "test_labels_read": False,
    }
    write_new(PANEL / "reward_interpretation_addendum.json", reward_addendum)
    cf_addendum = {
        "status": "PRELABEL_PUBLISHED_SURVIVAL_COMPARATOR_ADDENDUM_FROZEN",
        "protocol_sha256": protocol_hash,
        "test_labels_read": False,
        "reason": "Use the same predeclared four forecaster arms as the first fresh BRIDGE panel on five new tasks.",
        "published_source": {
            "paper": "https://arxiv.org/html/2601.22259v2",
            "repository": "https://github.com/dain20000222/TabularFM4Survival",
            "commit": "b27d69c27a5c39b87822b1aebf838e3dd900000e",
            "source_file": "static/static_xgboost_final.py",
        },
        "forecast_comparisons": [
            {"method": "published_xgboost_cf_2026_adapted_b2",
             "role": "published survival formulation adapted to seven classes with 18 generic pilot features",
             "prelabel_predictions": "artifacts/week8/bridge_expanded_published_xgboost_cf_preoutcome_2026-10-08/predictions_before_label_read.csv"},
            {"method": "xgboost_cf_2026_full108_architecture_control",
             "role": "same-108-input architecture control, dependent on OEH descriptors",
             "prelabel_predictions": "artifacts/week8/bridge_expanded_published_xgboost_cf_full108_preoutcome_2026-10-08/predictions_before_label_read.csv"},
        ],
        "fixed_test_grid": "five new published BRIDGE MDPs x five behaviors x BC/CFQI/IQL x six budgets and a right-censored class",
        "metrics": ["ordinal cumulative Brier", "seven-class log loss",
                    "MDP-cluster paired differences", "runtime"],
        "interpretation_limits": [
            "Published survival method is not offline-RL SOTA; its endpoint is adapted.",
            "Full-input control reuses OEH descriptors and is not independent.",
            "Five MDP-cluster intervals are descriptive; two BRIDGE cohorts are not a pre-registered simultaneous gate.",
            "No postlabel change to arms or task list.",
        ],
    }
    write_new(PANEL / "published_survival_comparator_addendum.json", cf_addendum)
    print(f"Frozen expanded protocol for {len(names)} new MDPs before labels: {protocol_hash}")


if __name__ == "__main__":
    main()
