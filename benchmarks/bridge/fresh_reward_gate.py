"""Prelabel reward-domain gate for the frozen BRIDGE candidate panel.

OEH's current posterior requires nonnegative rewards bounded by one. A
positive reward scaling preserves normalized return; reward shifting does not
preserve it when episode lengths differ. Tasks with negative rewards remain in
the audit registry as exclusions, never silently disappear.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import replace
from pathlib import Path

import numpy as np

from .fresh_adapter import DATA, PANEL, load_fresh_sticky_mdp, registry


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_eligible_mdp(name: str):
    gate = json.loads((PANEL / "reward_gate.json").read_text(encoding="utf-8"))
    row = next((x for x in gate["tasks"] if x["mdp_name"] == name), None)
    if row is None or row["status"] != "ELIGIBLE_NONNEGATIVE":
        raise ValueError(f"Task outside reward-eligible panel: {name}")
    path = DATA / name / "consolidated.npz"
    if sha256(path) != row["source_npz_sha256"]:
        raise ValueError("Source MDP changed after reward gate")
    mdp = load_fresh_sticky_mdp(name)
    scale = float(row["reward_scale_positive"])
    normalized = replace(mdp, R=mdp.R / scale,
                         metadata={**mdp.metadata, "reward_scale_positive": scale,
                                   "reward_normalization": "raw reward divided by published task maximum"})
    if np.any(normalized.R < 0) or np.any(normalized.R > 1 + 1e-12):
        raise ValueError("Reward outside OEH posterior bound after scaling")
    normalized.validate()
    return normalized


def main() -> None:
    output = PANEL / "reward_gate.json"
    if output.exists():
        raise FileExistsError(output)
    rows = []
    for name in registry():
        path = DATA / name / "consolidated.npz"
        with np.load(path, allow_pickle=False) as raw:
            rewards = raw["rewards"]
        minimum, maximum = float(rewards.min()), float(rewards.max())
        mdp = load_fresh_sticky_mdp(name)
        status = ("ELIGIBLE_NONNEGATIVE" if minimum >= 0 and maximum > 0
                  else "EXCLUDED_NEGATIVE_OR_ZERO_REWARD")
        rows.append({"mdp_name": name, "origin": mdp.metadata["origin"],
                     "status": status, "source_npz_sha256": sha256(path),
                     "reward_min_published": minimum, "reward_max_published": maximum,
                     "reward_scale_positive": maximum if status == "ELIGIBLE_NONNEGATIVE" else None,
                     "adapter_states": mdp.num_states,
                     "published_sticky_states": mdp.metadata["published_sticky_states"],
                     "published_minus_adapter_states": mdp.metadata["published_minus_adapter_states"],
                     "horizon": mdp.metadata["horizon"]})
    eligible = [row["mdp_name"] for row in rows if row["status"] == "ELIGIBLE_NONNEGATIVE"]
    if len(eligible) != 5:
        raise RuntimeError(f"Unexpected reward-compatible count: {len(eligible)}")
    document = {
        "status": "PRELABEL_FEASIBILITY_GATE_NO_LEARNER_LABELS",
        "candidate_registry_sha256": sha256(PANEL / "candidate_registry.csv"),
        "download_manifest_sha256": sha256(PANEL / "download_manifest.json"),
        "rule": "Keep all preselected candidates in audit; evaluate current OEH posterior only if published reward min>=0 and max>0; divide by public task maximum for posterior's [0,1] bound; no shift.",
        "eligible_tasks": eligible, "tasks": rows,
        "test_labels_read": False,
        "caveat": "Published MDPs are third-party; offline pilots and E_l labels will be generated by this project. Sticky-state adapter has a different reachable-state count from the author summary for some tasks and requires dynamics preflight before evaluation.",
    }
    output.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(f"Reward gate: {len(eligible)}/8 eligible; excluded negative-reward tasks: "
          f"{[row['mdp_name'] for row in rows if row['status'] != 'ELIGIBLE_NONNEGATIVE']}", flush=True)


if __name__ == "__main__":
    main()
