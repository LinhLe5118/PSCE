"""Write docs/final/FINAL_TESTS.md from the committed protocols, seals, labels, amendments and registered results.

    python -m scripts.reproduce.final_tests_doc            # rewrite the file
    python -m scripts.reproduce.final_tests_doc --check    # exit 1 if the committed file is not what the artifacts give

Every number and date in that file comes from the artifacts read here; the prose around them is fixed below.
"""
from __future__ import annotations

import argparse
import importlib
import sys
from pathlib import Path

import pandas as pd

from scripts.reproduce.common import ART, ROOT, TESTS, load_json, sha256
from scripts.reproduce.tables import registered_table

TARGET = ROOT / "docs/final/FINAL_TESTS.md"
SOURCES = {"internal": "project generator (new MDPs)", "colosseum2029": "Colosseum, sampler seed 2029",
           "spibb2": "SPIBB random MDPs with the authors' behavior policies", "forest": "MDPToolbox forest model",
           "frozenlake": "Gymnasium FrozenLake, random slippery maps", "gambler": "gambler's problem",
           "mdpp": "MDP Playground", "labmaze": "labmaze layouts with slippery four-way moves"}
DESIGN = {
    "Test 1": ("Fixed sequence of three steps; a step is tested only if the previous one passed. Step 1: OEH against the "
               "robust head on the pooled external MDPs. Step 2: OEH against the full head, at most 2% worse inside the "
               "generator and better outside it. Step 3: OEH against the Baseline, XGBoost-CF/18, LCE, Baseline + LCE, CB and Baseline + CB, "
               "inside and outside the generator. Scores: IBS and LL over all budgets."),
    "Test 2": ("Registered after Test 1 on two sources that played no part in development, although the Gymnasium "
               "FrozenLake maps resemble the Colosseum FrozenLake grids used in development. One family: OEH against the "
               "robust head on the 72 pooled MDPs, IBS and LL over all budgets."),
    "Test 3": ("Registered after Test 2 with new questions only; the contrast that failed in Test 2 is not tested again. "
               "Scores on the budgets from the pilot size up (IBS≥ and LLext). Fixed sequence: F1, OEH against "
               "Baseline + prefix/FQE; F2, OEH against the Baseline. F3 estimates the regret of the registered budget decision against both, "
               "with no pass rule."),
}


def _utc(stamp: str) -> str:
    return pd.Timestamp(stamp).tz_convert("UTC").strftime("%Y-%m-%d %H:%M UTC")


def build() -> str:
    spec = ROOT / "artifacts/week8/oeh_v2_development_2026-10-14/oeh_v2_spec.json"
    lines = [
        "# The three final tests",
        "",
        "Generated by `python -m scripts.reproduce.final_tests_doc` from the committed artifacts; do not edit by hand.",
        "",
        "Every test uses the same frozen method: the specification "
        f"[`oeh_v2_spec.json`](../../artifacts/week8/oeh_v2_development_2026-10-14/oeh_v2_spec.json) "
        f"(SHA-256 `{sha256(spec)[:12]}…`, frozen {_utc(load_json(spec)['frozen_at_utc'])}), the heads fitted on the 720 "
        "meta-training MDPs, and the single entry point `scripts/analysis/oeh_pipeline.py`.",
        "",
        "## Rules common to the three tests",
        "",
        "- The protocol (sources, sample sizes, comparators, scores, decision rule, bootstrap seed) was frozen and hashed "
        "before any data of the test existed.",
        "- For each source, the pilot-only inputs and every forecast were written and hashed in `preoutcome_seal.json` "
        "before any learner was trained on the test data; `outcome_run.json` links the labels to that seal.",
        "- A label is the first budget from which at least 8 of 10 runs reach a normalized return of 0.95 and keep it at "
        "every larger budget, or `>x50`.",
        "- Scores are averaged within each MDP, then across MDPs. A contrast is the score of the comparator minus the score "
        "of OEH, so a positive value favours OEH.",
        "- Bounds are simultaneous one-sided 95% lower bounds over the contrasts of a family (max-t with the original standard "
        "error, 10,000 resamples of whole MDPs). A family passes (GO) only if every lower bound is above zero.",
        "- A defect found after the freeze but before any outcome is fixed only by a recorded pre-outcome amendment.",
        "",
    ]
    for test, t in TESTS.items():
        folder = ART / t["folder"]
        protocol = load_json(folder / "protocol.json")
        seed = importlib.import_module(t["runner"]).BOOTSTRAP["seed"]
        result = load_json(folder / "result.json")
        lines += [f"## {test}", "", f"Folder: [`artifacts/{t['folder']}`](../../artifacts/{t['folder']}/). "
                  f"Bootstrap seed {seed}.", "", DESIGN[test], "",
                  "| Source | MDPs | Cases | Forecasts sealed | Labels opened |", "|---|---:|---:|---|---|"]
        total = [0, 0]
        for panel in t["panels"]:
            labels = pd.read_csv(folder / panel / "labels.csv")
            seal, run = load_json(folder / panel / "preoutcome_seal.json"), load_json(folder / panel / "outcome_run.json")
            total[0] += labels.mdp_id.nunique()
            total[1] += len(labels)
            lines.append(f"| {SOURCES[panel]} (`{panel}`) | {labels.mdp_id.nunique()} | {len(labels):,} | "
                         f"{_utc(seal['sealed_at_utc'])} | {_utc(run['completed_at_utc'])} |")
        lines += [f"| **Total** | **{total[0]}** | **{total[1]:,}** | | |", "",
                  f"Protocol frozen {_utc(protocol['frozen_at_utc'])} (SHA-256 `{sha256(folder / 'protocol.json')[:12]}…`); "
                  f"registered analysis completed {_utc(result['completed_at_utc'])}.", ""]
        amendments = sorted(folder.glob("preoutcome_amendment_*.json")) + sorted((folder / "amendments").glob("*.json"))
        for path in amendments:
            a = load_json(path)
            when = f", recorded {_utc(a['recorded_at_utc'])}" if "recorded_at_utc" in a else ""
            lines += [f"Amendment [`{path.relative_to(folder).as_posix()}`](../../{path.relative_to(ROOT).as_posix()}) "
                      f"(status: {a['status']}{when}). Problem: {a.get('problem', a.get('reason', '')).rstrip('.')}. "
                      f"Change: {a['change'].rstrip('.')}.", ""]
    results = {test: load_json(ART / t["folder"] / "result.json") for test, t in TESTS.items()}
    lines += ["## Registered results", "", *[row.replace(" vs B2", " vs Baseline") for row in registered_table(results)], "",
              "## What the evidence supports", "",
              "- Against generic pilot statistics (the Baseline, the same heads on the 18 statistics), OEH is better in the registered "
              "comparisons of Test 1 and Test 3. On Test 2 its log loss is lower than the Baseline's, but that comparison was not "
              "registered there and its IBS difference cannot be separated from zero.",
              "- Against the strongest baseline that also uses pilot learning curves (the robust head), the advantage depends on "
              "the source: Test 1 passed, with most of its margin from the forest model; Test 2 did not pass.",
              "- On Test 3, the full head alone, without the gate, scored better than OEH (descriptive, not registered).",
              "- Every MDP is small and tabular (at most 256 state–action pairs); each label is itself estimated from ten "
              "runs on a grid of six budgets.",
              "- The ablation, net-cost, learner-level and calibration analyses were run after the labels were opened; they "
              "are post hoc. `python -m scripts.reproduce` recomputes them.",
              ""]
    return "\n".join(lines)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            raise SystemExit(f"{TARGET.relative_to(ROOT)} is not what the artifacts give; rerun without --check")
        print("up to date")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("written", TARGET.relative_to(ROOT))


if __name__ == "__main__":
    main()
